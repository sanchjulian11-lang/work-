// Administrative bootstrap only. Never expose the service key or this script in a browser.
import { createClient } from "@supabase/supabase-js";
import { randomUUID } from "node:crypto";
const required = [
  "NEXT_PUBLIC_SUPABASE_URL",
  "SUPABASE_SERVICE_ROLE_KEY",
  "SEED_BROKER_EMAIL",
  "SEED_CLIENT_EMAIL",
  "SEED_PASSWORD",
];
for (const key of required)
  if (!process.env[key]) throw new Error(`Set ${key} securely before seeding`);
if (process.env.DEMO_MODE === "true")
  throw new Error("Use connected mode to seed Supabase");
const db = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL,
  process.env.SUPABASE_SERVICE_ROLE_KEY,
  { auth: { persistSession: false } },
);
const { data: existing, error: readError } = await db
  .from("organizations")
  .select("id")
  .limit(1);
if (readError) throw readError;
if (existing.length)
  throw new Error(
    "Bootstrap only runs against a fresh database; refusing to duplicate accounts.",
  );
// Generated by `npm run export-seed`; imports use the same domain fixture and rules.
const { readFile } = await import("node:fs/promises");
const seed = JSON.parse(
  await readFile(new URL("../supabase/fixture.json", import.meta.url), "utf8"),
);
const orgId = randomUUID();
function check(result) {
  if (result.error) throw result.error;
  return result.data;
}
check(
  await db
    .from("organizations")
    .insert({ id: orgId, name: "Fictional Brokerage Sandbox" }),
);
const broker = check(
  await db.auth.admin.createUser({
    email: process.env.SEED_BROKER_EMAIL,
    password: process.env.SEED_PASSWORD,
    email_confirm: true,
  }),
).user;
const client = check(
  await db.auth.admin.createUser({
    email: process.env.SEED_CLIENT_EMAIL,
    password: process.env.SEED_PASSWORD,
    email_confirm: true,
  }),
).user;
check(
  await db.from("memberships").insert([
    { user_id: broker.id, organization_id: orgId, role: "broker" },
    { user_id: client.id, organization_id: orgId, role: "client" },
  ]),
);
check(
  await db
    .from("industry_rules")
    .insert({
      version: seed.business.rulesVersion,
      industry: "contractors_and_trades",
      provenance: "Internal starter rules; not insurer-approved",
      rules: seed.rules,
    }),
);
const business = {
  ...seed.business,
  organizationId: orgId,
  assignedClientIds: [client.id],
};
for (const answer of Object.values(business.answers))
  answer.recordedBy = client.id;
check(
  await db
    .from("businesses")
    .insert({ id: business.id, organization_id: orgId, state: business }),
);
console.log(
  "Created fictional brokerage, broker/client sign-ins, pinned rules, and HVAC sample. No emails sent.",
);
